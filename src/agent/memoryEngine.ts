export function parseReflectOps(raw: string): ReflectOp[] {
	if (!raw) return [];
	const start = raw.indexOf("[");
	const end = raw.lastIndexOf("]");
	if (start < 0 || end <= start) return [];
	let parsed: unknown;
	try {
		parsed = JSON.parse(raw.slice(start, end + 1));
	} catch {
		return [];
	}
	if (!Array.isArray(parsed)) return [];
	const out: ReflectOp[] = [];
	for (const item of parsed) {
		if (!item || typeof item !== "object" || Array.isArray(item)) continue;
		const o = item as Record<string, unknown>;
		if (o.op === "obs") {
			const text = typeof o.text === "string" ? o.text.trim().slice(0, 500) : "";
			if (!text) continue;
			const factIds = Array.isArray(o.factIds)
				? (o.factIds as unknown[]).filter((x): x is string => typeof x === "string").slice(0, 50)
				: [];
			const proofs = Array.isArray(o.proofs)
				? (o.proofs as unknown[]).filter((x): x is string => typeof x === "string").map((x) => x.slice(0, 300)).slice(0, 50)
				: [];
			const replaceId = typeof o.replaceId === "string" && o.replaceId ? o.replaceId : undefined;
			out.push({ op: "obs", text, factIds, proofs, replaceId });
		} else if (o.op === "obsDelete") {
			const id = typeof o.id === "string" ? o.id : "";
			if (!id) continue;
			out.push({ op: "obsDelete", id });
		} else if (o.op === "model") {
			const question = typeof o.question === "string" ? o.question.trim() : "";
			const answer = typeof o.answer === "string" ? o.answer.trim().slice(0, 1000) : "";
			if (!question || !answer) continue;
			if (!MENTAL_MODEL_QUESTIONS.includes(question)) continue; // bounded, read-cheap set
			out.push({ op: "model", question, answer });
		}
	}
	return out;
}

export function applyReflectOps(
	observations: EngineObservation[],
	models: EngineMentalModel[],
	ops: ReflectOp[],
	now: number,
	genId: (prefix: string) => string
): { observations: EngineObservation[]; models: EngineMentalModel[]; obsAdded: number; obsUpdated: number; obsDeleted: number; modelsUpdated: number } {
	const obs = [...observations];
	const mods = [...models];
	let obsAdded = 0;
	let obsUpdated = 0;
	let obsDeleted = 0;
	let modelsUpdated = 0;
	for (const op of ops) {
		if (op.op === "obs") {
			const existing = op.replaceId ? obs.find((x) => x.id === op.replaceId) : undefined;
			if (existing) {
				existing.text = op.text;
				existing.factIds = [...new Set([...existing.factIds, ...op.factIds])];
				existing.proofs = [...new Set([...existing.proofs, ...op.proofs])].slice(0, 50);
				existing.proofCount = existing.factIds.length;
				existing.updatedAt = now;
				obsUpdated++;
			} else {
				obs.push({
					id: genId("o"),
					text: op.text,
					factIds: op.factIds,
					proofs: op.proofs.slice(0, 50),
					proofCount: op.factIds.length,
					trust: 0.5,
					createdAt: now,
					updatedAt: now,
				});
				obsAdded++;
			}
		} else if (op.op === "obsDelete") {
			const i = obs.findIndex((x) => x.id === op.id);
			if (i >= 0) {
				obs.splice(i, 1);
				obsDeleted++;
			}
		} else if (op.op === "model") {
			const existing = mods.find((m) => m.question === op.question);
			if (existing) {
				existing.answer = op.answer;
				existing.updatedAt = now;
			} else {
				mods.push({ id: genId("m"), question: op.question, answer: op.answer, updatedAt: now });
			}
			modelsUpdated++;
		}
	}
	if (obs.length > MAX_ENGINE_OBSERVATIONS) {
		obs.sort((a, b) => b.updatedAt - a.updatedAt);
		obs.length = MAX_ENGINE_OBSERVATIONS;
	}
	if (mods.length > MAX_ENGINE_MODELS) {
		mods.sort((a, b) => b.updatedAt - a.updatedAt);
		mods.length = MAX_ENGINE_MODELS;
	}
	return { observations: obs, models: mods, obsAdded, obsUpdated, obsDeleted, modelsUpdated };
}

/* ── mental model block (read-cheap, no LLM) ───────────────────────────── */

export function buildMentalModelBlock(models: EngineMentalModel[], maxChars = 1500): string | null {
	const withAnswers = models.filter((m) => m.answer.trim().length > 0);
	if (withAnswers.length === 0) return null;
	let body = "";
	for (const m of withAnswers) {
		const line = `- ${m.question} → ${m.answer}`;
		if (body.length + line.length + 1 > maxChars) break;
		body += (body ? "\n" : "") + line;
	}
	if (!body) return null;
	return `Mental models (settled knowledge from memory):\n${body}`;
}

/* ── observations / models / meta JSONL ────────────────────────────────── */

function validObservation(o: unknown): o is EngineObservation {
	if (!o || typeof o !== "object" || Array.isArray(o)) return false;
	const r = o as Record<string, unknown>;
	return (
		typeof r.id === "string" &&
		typeof r.text === "string" &&
		r.text.trim().length > 0 &&
		Array.isArray(r.factIds) &&
		Array.isArray(r.proofs) &&
		typeof r.proofCount === "number" &&
		typeof r.trust === "number" &&
		typeof r.createdAt === "number" &&
		typeof r.updatedAt === "number"
	);
}

function validMentalModel(m: unknown): m is EngineMentalModel {
	if (!m || typeof m !== "object" || Array.isArray(m)) return false;
	const r = m as Record<string, unknown>;
	return typeof r.id === "string" && typeof r.question === "string" && typeof r.answer === "string" && typeof r.updatedAt === "number";
}

function parseJsonl<T>(text: string, valid: (x: unknown) => x is T): T[] {
	const out: T[] = [];
	for (const line of text.split("\n")) {
		const t = line.trim();
		if (!t) continue;
		try {
			const v = JSON.parse(t);
			if (valid(v)) out.push(v);
		} catch {
			/* skip corrupt lines */
		}
	}
	return out;
}

export function parseObservationsJsonl(text: string): EngineObservation[] {
	return parseJsonl(text, validObservation);
}

export function parseModelsJsonl(text: string): EngineMentalModel[] {
	return parseJsonl(text, validMentalModel);
}

export function serializeObservationsJsonl(obs: EngineObservation[]): string {
	return obs.map((o) => JSON.stringify(o)).join("\n") + (obs.length ? "\n" : "");
}

export function serializeModelsJsonl(models: EngineMentalModel[]): string {
	return models.map((m) => JSON.stringify(m)).join("\n") + (models.length ? "\n" : "");
}

export function parseMeta(text: string): EngineMeta | null {
	if (!text) return null;
	try {
		const o = JSON.parse(text) as Record<string, unknown>;
		if (typeof o.lastReflectAt !== "number" || typeof o.factCountAtReflect !== "number") return null;
		return { lastReflectAt: o.lastReflectAt, factCountAtReflect: o.factCountAtReflect };
	} catch {
		return null;
	}
}

export function serializeMeta(meta: EngineMeta): string {
	return JSON.stringify(meta);
}

/* ── recall injection ──────────────────────────────────────────────────── */

export const RECALL_PREAMBLE =
	"# Persistent memory (recalled for this message)\n" +
	"Use this to answer questions about the user and prior sessions. Do not call tools to look up information that is already present here.";

/** Facts that survive the injection scan (threatPatterns, same as MEMORY.md). */
export function recallableFacts(facts: EngineFact[]): EngineFact[] {
	return facts.filter((f) => !firstThreatMessage(f.text));
}

/** Format the injected block; null when nothing survives the scan/cap.
 *  v0.1.178: also lists consolidated observations under their own header. */
export function buildRecallBlock(
	facts: EngineFact[],
	observations: EngineObservation[] = [],
	maxChars = 3000
): string | null {
	const cleanF = facts.filter((f) => !firstThreatMessage(f.text));
	const cleanO = observations.filter((o) => !firstThreatMessage(o.text));
	if (cleanF.length === 0 && cleanO.length === 0) return null;
	const lines: string[] = [];
	for (const f of cleanF) lines.push(`- ${f.text}`);
	if (cleanO.length > 0) {
		lines.push("Consolidated observations:");
		for (const o of cleanO) lines.push(`- ${o.text}`);
	}
	let body = "";
	for (const line of lines) {
		if (body.length + line.length + 1 > maxChars) break;
		body += (body ? "\n" : "") + line;
	}
	if (!body) return null;
	return `${RECALL_PREAMBLE}\n\n${body}`;
}

/* ── vault store ───────────────────────────────────────────────────────── */

export class EngineMemoryStore {
	private folder: string;
	private seq = 0;

	constructor(
		private app: App,
		folder: string,
		private now: () => number = () => Date.now()
	) {
		this.folder = canonicalVaultPath(folder, { label: "Managed memory folder" });
	}

	setFolder(folder: string): void {
		this.folder = canonicalVaultPath(folder, { label: "Managed memory folder" });
	}

	get currentFolder(): string {
		return this.folder;
	}

	private factsPath(): string {
		const p = canonicalVaultPath(`${this.folder}/.engine/facts.jsonl`, { label: "Engine memory file" });
		if (!pathContains(this.folder, p)) throw new Error("Engine memory path escaped its folder.");
		return p;
	}

	private enginePath(fileName: string): string {
		const p = canonicalVaultPath(`${this.folder}/.engine/${fileName}`, { label: "Engine memory file" });
		if (!pathContains(this.folder, p)) throw new Error("Engine memory path escaped its folder.");
		return p;
	}

	private async readFile(path: string): Promise<string> {
		try {
			if (!(await this.app.vault.adapter.exists(path))) return "";
			return await this.app.vault.adapter.read(path);
		} catch {
			return "";
		}
	}

	async load(): Promise<EngineFact[]> {
		return parseFactsJsonl(await this.readFile(this.factsPath()));
	}

	async loadObservations(): Promise<EngineObservation[]> {
		return parseObservationsJsonl(await this.readFile(this.enginePath("observations.jsonl")));
	}

	async loadModels(): Promise<EngineMentalModel[]> {
		return parseModelsJsonl(await this.readFile(this.enginePath("models.jsonl")));
	}

	async loadMeta(): Promise<EngineMeta | null> {
		return parseMeta(await this.readFile(this.enginePath("meta.json")));
	}

	/** Fusion recall (BM25 + entity + temporal + trust); when `embed` is
	 *  provided, candidates are re-ranked with cosine similarity (Fase 3).
	 *  No LLM in either path — embedding is optional and injected. */
	async search(query: string, limit = 8, embed?: EmbedFn): Promise<EngineFact[]> {
		let ranked = rankFacts(query, await this.load(), this.now(), Math.max(limit * 3, 20));
		if (embed) ranked = await fuseScores(query, ranked, (r) => r.fact.text, embed);
		return ranked.slice(0, limit).map((r) => r.fact);
	}

	/** v0.1.178: consolidated observations recalled the same fused way. */
	async searchObservations(query: string, limit = 4, embed?: EmbedFn): Promise<EngineObservation[]> {
		let ranked = rankObservations(query, await this.loadObservations(), this.now(), Math.max(limit * 3, 12));
		if (embed) ranked = await fuseScores(query, ranked, (r) => r.obs.text, embed);
		return ranked.slice(0, limit).map((r) => r.obs);
	}

	/** One LLM call distills a turn into typed ops, then persists. */
	async retain(
		turnText: string,
		llm: EngineLLM,
		opts: { signal?: AbortSignal; maxInventoryChars?: number } = {}
	): Promise<RetainCounts> {
		const facts = await this.load();
		const messages = buildRetainPrompt(turnText, facts, opts.maxInventoryChars);
		const raw = await llm(messages, opts.signal);
		const ops = parseRetainOps(raw);
		if (ops.length === 0) return { added: 0, updated: 0, deleted: 0 };
		const result = applyRetainOps(facts, ops, this.now(), () => this.genId("f"));
		await this.writeFile(this.factsPath(), serializeFactsJsonl(result.facts));
		return { added: result.added, updated: result.updated, deleted: result.deleted };
	}

	/** Fase 2: one LLM call consolidates facts → observations and answers the
	 *  standing mental-model questions. Silent on any failure (best-effort). */
	async reflect(
		llm: EngineLLM,
		opts: { signal?: AbortSignal } = {}
	): Promise<{ obsAdded: number; obsUpdated: number; obsDeleted: number; modelsUpdated: number } | null> {
		const [facts, observations, models, meta] = await Promise.all([
			this.load(),
			this.loadObservations(),
			this.loadModels(),
			this.loadMeta(),
		]);
		const now = this.now();
		if (!consolidationDue(facts, meta, now)) return null;
		const messages = buildReflectPrompt(facts, observations, models);
		const raw = await llm(messages, opts.signal);
		const ops = parseReflectOps(raw);
		if (ops.length === 0) {
			/* still mark the pass so a silent "[]" doesn't re-fire every turn */
			await this.writeFile(this.enginePath("meta.json"), serializeMeta({ lastReflectAt: now, factCountAtReflect: facts.length }));
			return { obsAdded: 0, obsUpdated: 0, obsDeleted: 0, modelsUpdated: 0 };
		}
		const result = applyReflectOps(observations, models, ops, now, (p) => this.genId(p));
		await this.writeFile(this.enginePath("observations.jsonl"), serializeObservationsJsonl(result.observations));
		await this.writeFile(this.enginePath("models.jsonl"), serializeModelsJsonl(result.models));
		await this.writeFile(this.enginePath("meta.json"), serializeMeta({ lastReflectAt: now, factCountAtReflect: facts.length }));
		return {
			obsAdded: result.obsAdded,
			obsUpdated: result.obsUpdated,
			obsDeleted: result.obsDeleted,
			modelsUpdated: result.modelsUpdated,
		};
	}

	/** Settled knowledge, read straight from disk — no LLM at retrieval time. */
	async mentalModelsBlock(maxChars = 1500): Promise<string | null> {
		return buildMentalModelBlock(await this.loadModels(), maxChars);
	}

	private genId(prefix: string): string {
		this.seq = (this.seq + 1) % 46656;
		return `${prefix}-${this.now().toString(36)}-${this.seq.toString(36)}`;
	}

	private async writeFile(path: string, text: string): Promise<void> {
		const dir = path.split("/").slice(0, -1).join("/");
		if (dir) await this.app.vault.adapter.mkdir(dir).catch(() => {});
		await this.app.vault.adapter.write(path, text);
	}
}

/** True for greetings/acks/slash-commands — no recall/retain value. */
export function isTrivialPrompt(text: string | null | undefined): boolean {
	if (!text) return true;
	const stripped = text.trim();
	if (!stripped) return true;
	if (stripped.startsWith("/")) return true;
	return TRIVIAL_PROMPT_RE.test(stripped);
}

/* ── text helpers ───────────────────────────────────────────────────────── */

export function tokenize(text: string): string[] {
	return (text.toLowerCase().match(/[a-z0-9]+/g) ?? []).filter((t) => t.length >= 2);
}

/** Canonical dedupe key: lowercase, alnum tokens collapsed. */
export function factKey(text: string): string {
	return text
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, " ")
		.trim()
		.split(/\s+/)
		.join(" ");
}

function clamp01(n: number): number {
	return Number.isFinite(n) ? Math.min(1, Math.max(0, n)) : 0.5;
}

/* ── BM25 ──────────────────────────────────────────────────────────────── */

function termFreq(tokens: string[]): Map<string, number> {
	const m = new Map<string, number>();
	for (const t of tokens) m.set(t, (m.get(t) ?? 0) + 1);
	return m;
}

/** Simplified BM25 over a corpus of token lists (k1=1.5, b=0.75). */
export function bm25(queryTokens: string[], docTokens: string[], corpus: string[][]): number {
	if (queryTokens.length === 0 || docTokens.length === 0 || corpus.length === 0) return 0;
	const k1 = 1.5;
	const b = 0.75;
	const avgdl = corpus.reduce((s, d) => s + d.length, 0) / corpus.length;
	const tf = termFreq(docTokens);
	const df = new Map<string, number>();
	for (const d of corpus) for (const t of new Set(d)) df.set(t, (df.get(t) ?? 0) + 1);
	let score = 0;
	for (const t of new Set(queryTokens)) {
		const f = tf.get(t) ?? 0;
		if (f === 0) continue;
		const n = df.get(t) ?? 0;
		const idf = Math.log(1 + (corpus.length - n + 0.5) / (n + 0.5));
		score += (idf * (f * (k1 + 1))) / (f + k1 * (1 - b + b * (docTokens.length / avgdl)));
	}
	return score;
}

/* ── scoring fusion ─────────────────────────────────────────────────────── */

/** Count of the fact's entities that appear in the (lowercased) query. */
export function entityOverlap(queryLower: string, fact: EngineFact): number {	if (fact.entities.length === 0) return 0;
	let hits = 0;
	for (const e of fact.entities) {
		if (e && queryLower.includes(e.toLowerCase())) hits++;
	}
	return hits;
}

/** Recency weight — half-life of 30 days. */
export function temporalWeight(updatedAt: number, now: number, halfLifeDays = 30): number {
	const ageDays = Math.max(0, (now - updatedAt) / 86_400_000);
	return Math.pow(0.5, ageDays / halfLifeDays);
}

export interface RankedFact {
	fact: EngineFact;
	score: number;
}

/** Fuse BM25 + entity overlap + recency, scaled by trust. Zero-latency. */
export function rankFacts(query: string, facts: EngineFact[], now: number, limit = 8): RankedFact[] {
	const ql = query.toLowerCase();
	const queryTokens = tokenize(query);
	const corpus = facts.map((f) => tokenize(f.text));
	return facts
		.map((fact) => {
			const b = bm25(queryTokens, tokenize(fact.text), corpus);
			const e = entityOverlap(ql, fact);
			const t = temporalWeight(fact.updatedAt, now);
			const trust = clamp01(fact.trust);
			const score = (Math.log1p(b) * 3 + e * 2.5 + t) * (0.5 + trust * 0.5);
			return { fact, score };
		})
		.filter((r) => r.score > 0)
		.sort((a, b) => b.score - a.score)
		.slice(0, limit);
}

/** v0.1.178 (Fase 3): an embedding provider — one vector per input (null for
 *  a missing entry), or null on failure. Optional; recall falls back to pure
 *  fusion when absent. */
export type EmbedFn = (texts: string[]) => Promise<(number[] | null)[] | null>;

/** Cosine similarity in [0..1]; 0 on empty/zero-norm vectors. */
export function cosineSimilarity(a: number[], b: number[]): number {
	if (!a || !b || a.length === 0 || b.length === 0 || a.length !== b.length) return 0;
	let dot = 0;
	let na = 0;
	let nb = 0;
	for (let i = 0; i < a.length; i++) {
		dot += a[i] * b[i];
		na += a[i] * a[i];
		nb += b[i] * b[i];
	}
	if (na === 0 || nb === 0) return 0;
	return Math.max(0, dot / (Math.sqrt(na) * Math.sqrt(nb)));
}

/** Re-rank already-scored candidates with semantic similarity: score is
 *  multiplied by (1 + cosine), so a strong lexical hit stays, and a near-
 *  synonym that BM25 missed can climb. Pure of transport (embed injected). */
export async function fuseScores<T extends { score: number }>(
	query: string,
	ranked: T[],
	textOf: (r: T) => string,
	embed: EmbedFn
): Promise<T[]> {
	if (ranked.length === 0) return ranked;
	const vecs = await embed([query, ...ranked.map(textOf)]);
	if (!vecs || !vecs[0]) return ranked;
	const q = vecs[0];
	return ranked
		.map((r, i) => {
			const v = vecs[i + 1];
			if (!v) return r;
			const c = cosineSimilarity(q, v);
			return { ...r, score: r.score * (1 + c) };
		})
		.sort((a, b) => b.score - a.score);
}

export interface RankedObservation {
	obs: EngineObservation;
	score: number;
}

/** BM25 + recency + trust over observation texts (observations carry no
 *  entities — they are consolidated prose). */
export function rankObservations(query: string, observations: EngineObservation[], now: number, limit = 4): RankedObservation[] {
	const queryTokens = tokenize(query);
	const corpus = observations.map((o) => tokenize(o.text));
	return observations
		.map((obs) => {
			const b = bm25(queryTokens, tokenize(obs.text), corpus);
			const t = temporalWeight(obs.updatedAt, now);
			const trust = clamp01(obs.trust);
			const score = (Math.log1p(b) * 3 + t) * (0.5 + trust * 0.5);
			return { obs, score };
		})
		.filter((r) => r.score > 0)
		.sort((a, b) => b.score - a.score)
		.slice(0, limit);
}

/* ── contradiction hint (Holographic) ──────────────────────────────────── */

const NEG_WORDS = ["not", "no", "never", "don't", "dont", "doesn't", "doesnt", "dislike", "dislikes", "hate", "hates", "stop", "stopped", "without"];

const negWordRe = (w: string) => new RegExp(`\\b${w}\\b`, "i");

/** Cheap lexical negation-flip heuristic: one negated, the other not, with
 *  ≥2 significant words in common. Used as a reconcile hint, not a verdict —
 *  the LLM decides update/delete during retain. */
export function contradicts(a: string, b: string): boolean {
	const na = NEG_WORDS.some((w) => negWordRe(w).test(a));
	const nb = NEG_WORDS.some((w) => negWordRe(w).test(b));
	if (na === nb) return false;
	const negSet = new Set(NEG_WORDS);
	const wa = new Set(tokenize(a).filter((w) => !negSet.has(w)));
	const wb = new Set(tokenize(b).filter((w) => !negSet.has(w)));
	let overlap = 0;
	for (const w of wa) if (wb.has(w)) overlap++;
	return overlap >= 2;
}

/* ── JSONL (facts file) ────────────────────────────────────────────────── */

function validFact(f: unknown): f is EngineFact {
	if (!f || typeof f !== "object" || Array.isArray(f)) return false;
	const o = f as Record<string, unknown>;
	return (
		typeof o.id === "string" &&
		(o.kind === "world" || o.kind === "experience") &&
		typeof o.text === "string" &&
		o.text.trim().length > 0 &&
		Array.isArray(o.entities) &&
		typeof o.trust === "number" &&
		typeof o.createdAt === "number" &&
		typeof o.updatedAt === "number"
	);
}

export function parseFactsJsonl(text: string): EngineFact[] {
	const out: EngineFact[] = [];
	for (const line of text.split("\n")) {
		const t = line.trim();
		if (!t) continue;
		try {
			const f = JSON.parse(t);
			if (validFact(f)) out.push(f);
		} catch {
			/* skip a corrupt line — append-only file, never hard-fail */
		}
	}
	return out;
}

export function serializeFactsJsonl(facts: EngineFact[]): string {
	return facts.map((f) => JSON.stringify(f)).join("\n") + (facts.length ? "\n" : "");
}

/* ── retain ops ────────────────────────────────────────────────────────── */

/** Apply validated ops; add dedupes by canonical key (turns into an update),
 *  then prunes to MAX_ENGINE_FACTS keeping the most recently touched. */
export function applyRetainOps(
	facts: EngineFact[],
	ops: RetainOp[],
	now: number,
	genId: () => string
): { facts: EngineFact[]; added: number; updated: number; deleted: number } {
	let added = 0;
	let updated = 0;
	let deleted = 0;
	const out = [...facts];
	for (const op of ops) {
		if (op.op === "add") {
			const key = factKey(op.text);
			const dup = out.find((f) => factKey(f.text) === key);
			if (dup) {
				dup.text = op.text;
				dup.kind = op.kind;
				dup.entities = op.entities;
				dup.updatedAt = now;
				updated++;
			} else {
				out.push({
					id: genId(),
					kind: op.kind,
					text: op.text,
					entities: op.entities,
					trust: 0.5,
					createdAt: now,
					updatedAt: now,
				});
				added++;
			}
		} else if (op.op === "update") {
			const f = out.find((x) => x.id === op.id);
			if (f) {
				f.text = op.text;
				f.updatedAt = now;
				updated++;
			}
		} else if (op.op === "delete") {
			const i = out.findIndex((x) => x.id === op.id);
			if (i >= 0) {
				out.splice(i, 1);
				deleted++;
			}
		}
	}
	if (out.length > MAX_ENGINE_FACTS) {
		out.sort((a, b) => b.updatedAt - a.updatedAt);
		out.length = MAX_ENGINE_FACTS;
	}
	return { facts: out, added, updated, deleted };
}


/** Parse a JSON array of ops out of an LLM reply (first `[…]` span). */
export function parseRetainOps(raw: string): RetainOp[] {
	if (!raw) return [];
	const start = raw.indexOf("[");
	const end = raw.lastIndexOf("]");
	if (start < 0 || end <= start) return [];
	let parsed: unknown;
	try {
		parsed = JSON.parse(raw.slice(start, end + 1));
	} catch {
		return [];
	}
	if (!Array.isArray(parsed)) return [];
	const out: RetainOp[] = [];
	for (const item of parsed) {
		if (!item || typeof item !== "object" || Array.isArray(item)) continue;
		const o = item as Record<string, unknown>;
		if (o.op === "add") {
			const text = typeof o.text === "string" ? o.text.trim().slice(0, 500) : "";
			if (!text) continue;
			const kind: FactKind = o.kind === "experience" ? "experience" : "world";
			const entities = Array.isArray(o.entities)
				? (o.entities as unknown[])
						.filter((e): e is string => typeof e === "string")
						.map((e) => e.trim())
						.filter(Boolean)
						.slice(0, 5)
				: [];
			out.push({ op: "add", kind, text, entities });
		} else if (o.op === "update") {
			const id = typeof o.id === "string" ? o.id : "";
			const text = typeof o.text === "string" ? o.text.trim().slice(0, 500) : "";
			if (!id || !text) continue;
			out.push({ op: "update", id, text });
		} else if (o.op === "delete") {
			const id = typeof o.id === "string" ? o.id : "";
			if (!id) continue;
			out.push({ op: "delete", id });
		}
	}
	return out;
}

/* ── reflect ops (Fase 2) ──────────────────────────────────────────────── */

export type ReflectOp =
	| { op: "obs"; text: string; factIds: string[]; proofs: string[]; replaceId?: string }
	| { op: "obsDelete"; id: string }
	| { op: "model"; question: string; answer: string };

/** Reflect cadence: consolidate when enough facts exist and enough have
 *  accumulated since the last pass (or a cooldown elapsed with new facts). */
export function consolidationDue(facts: EngineFact[], meta: EngineMeta | null, now: number): boolean {
	if (facts.length === 0) return false;
	if (!meta) return facts.length >= 8;
	const dirty = facts.length - meta.factCountAtReflect;
	if (dirty <= 0) return false;
	if (dirty >= 5) return true;
	return now - (meta.lastReflectAt ?? 0) > 10 * 60_000;
}


/**
 * Extract the subset of Obsidian's app.css that can actually reach into
 * plugin views (bare-element rules + theme variable blocks), producing
 * test/obsidian-sim.css. The preview harness loads this BEFORE the plugin's
 * styles.css, reproducing Obsidian's real cascade environment.
 *
 * Source: test/reference-obsidian-app.css (app.css captured from dev tools).
 */
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("./reference-obsidian-app.css", import.meta.url), "utf8");
const css = src.replace(/\/\*[\s\S]*?\*\//g, ""); // strip comments

function keptSelector(sel) {
	return sel.split(",").some((raw) => {
		const s = raw.trim();
		if (!s) return false;
		if (/^(\*|:root|html|body)\b/.test(s)) return true; // var/root blocks
		if (/^\.theme-(dark|light)$/.test(s)) return true; // theme palettes
		// bare-element rules that can hit our DOM
		if (/^(button|input|textarea|select|svg\.svg-icon|a|hr|ul|ol)(?![\w-])/.test(s)) return true;
		// markdown-rendered elements that plugins display inside their views
		// (our chat renders .markdown-rendered blockquote; without the official
		// rule the preview silently loses the accent quote bar — 2026-07-21)
		if (/^\.markdown-rendered\s+blockquote\b/.test(s)) return true;
		return false;
	});
}

function findClose(text, openIdx) {
	let depth = 0;
	for (let i = openIdx; i < text.length; i++) {
		if (text[i] === "{") depth++;
		else if (text[i] === "}") {
			depth--;
			if (depth === 0) return i;
		}
	}
	throw new Error("unbalanced braces at " + openIdx);
}

/** Parse top-level blocks: rules and at-blocks. */
function parseBlocks(text) {
	const blocks = [];
	let i = 0;
	while (i < text.length) {
		while (i < text.length && /\s/.test(text[i])) i++;
		if (i >= text.length) break;
		const brace = text.indexOf("{", i);
		const semi = text.indexOf(";", i);
		if (brace === -1) break;
		if (semi !== -1 && semi < brace) {
			// at-statement like @import ...;
			i = semi + 1;
			continue;
		}
		const prelude = text.slice(i, brace).trim();
		const close = findClose(text, brace);
		const inner = text.slice(brace + 1, close);
		blocks.push({ prelude, inner });
		i = close + 1;
	}
	return blocks;
}

function extract(text) {
	const out = [];
	for (const b of parseBlocks(text)) {
		if (/^@(media|supports)\b/.test(b.prelude)) {
			const inner = extract(b.inner);
			if (inner.length) out.push(`${b.prelude} {\n${inner.join("\n")}\n}`);
		} else if (/^@(keyframes|font-face|page|property|layer)\b/.test(b.prelude)) {
			continue; // not needed for fidelity
		} else if (keptSelector(b.prelude)) {
			out.push(`${b.prelude} {\n${b.inner.trim()}\n}`);
		}
	}
	return out;
}

const kept = extract(css);
const header = `/* ============================================================
 * AUTO-GENERATED by test/extract-obsidian-sim.mjs
 * Invasive subset of Obsidian ${new Date().toISOString().slice(0, 10)} app.css:
 * only rules that can style elements inside a plugin view
 * (bare button/input/textarea/select/svg/a/hr/ul/ol + theme vars).
 * Loaded before styles.css in the preview/ pages to reproduce
 * Obsidian's real cascade. Do not edit by hand.
 * ============================================================ */\n`;
const file = header + kept.join("\n\n") + "\n";
writeFileSync(new URL("./obsidian-sim.css", import.meta.url), file);

